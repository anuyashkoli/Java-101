package Tsundoku.data;

public class Book {
    String Title;
    String subTitle;
    String Author;
    float Price;
    int lastPage;

    public Book(String title, String subtitle, String author, float price, int lastpage) {
        Title = title;
        subTitle = subtitle;
        Author = author;
        Price = price;
        lastPage = lastpage;
    }
}


